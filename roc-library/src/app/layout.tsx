import type { Metadata } from "next";
import "./globals.css";
import localFont from "next/font/local";
import NavBarPage from "@/layout/navbar/navbar";
import SidebarPage from "@/layout/sidebar/sidebar";
import { LoadingProvider } from "@/context/LoadingContext";
import { LoadingOverlay, NavigationContent, NavigationProgress } from "@/components/Loader";
import { themeInitScript } from "@/components/ThemeToggle";
import { ToTopButton } from "@/components/ToTopButton";
import { GoogleAnalytics } from "@next/third-parties/google";

// Visit tracking runs only on the live production site: never in `npm run dev`
// and never on Vercel preview deployments. The ID is public, so it is safe to
// default here; set NEXT_PUBLIC_GA_MEASUREMENT_ID to override it.
const GA_MEASUREMENT_ID =
  process.env.NEXT_PUBLIC_GA_MEASUREMENT_ID ?? "G-HY2J341C5V";
const trackVisits =
  process.env.NODE_ENV === "production" &&
  (process.env.VERCEL_ENV === undefined ||
    process.env.VERCEL_ENV === "production");

const mali = localFont({
  src: "../../public/font/Mali-Regular.ttf",
  variable: "--font-tcs4",
  weight: "400",
  style: "normal",
});

export const metadata: Metadata = {
  // Share-card images (opengraph-image.png / twitter-image.png) need an absolute URL.
  // On Vercel, Next derives it automatically; set NEXT_PUBLIC_SITE_URL for a custom domain.
  ...(process.env.NEXT_PUBLIC_SITE_URL && {
    metadataBase: new URL(process.env.NEXT_PUBLIC_SITE_URL),
  }),
  title: "ROC-By Bozm",
  description: "Generated by bozm",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="th" data-theme="roc-light" suppressHydrationWarning>
      <head>
        <script dangerouslySetInnerHTML={{ __html: themeInitScript }} />
      </head>
      <body
        className={`${mali.className} antialiased m-0 p-0 h-screen`}
      >
        <LoadingProvider>
          <NavigationProgress />
          <LoadingOverlay />
          <ToTopButton />
          <div className="drawer h-screen">
            <input
              id="is-drawer-open"
              type="checkbox"
              className="drawer-toggle"
            />

            {/* Content */}
            <div className="drawer-content flex flex-col h-full">
              {/* Navbar */}
              <NavBarPage />

              {/* Page Content */}
              <div className="flex-1 bg-base-200 pt-16">
                <NavigationContent>{children}</NavigationContent>
              </div>
            </div>

            {/* Sidebar */}
            <div className="drawer-side">
              <label
                htmlFor="is-drawer-open"
                aria-label="close sidebar"
                className="drawer-overlay"
              ></label>
              <div className="bg-base-100 border-r border-base-300 min-h-full w-64 text-base-content flex flex-col">
                <SidebarPage />
              </div>
            </div>
          </div>
        </LoadingProvider>
      </body>
      {trackVisits && <GoogleAnalytics gaId={GA_MEASUREMENT_ID} />}
    </html>
  );
}
